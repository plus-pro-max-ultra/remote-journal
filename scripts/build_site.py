#!/usr/bin/env python3
"""Validate published article JSON and build the static website output."""
from pathlib import Path
import json, shutil, sys
ROOT = Path(__file__).resolve().parents[1]
ARTICLES = ROOT / "content" / "articles"
ASSETS = ["index.html", "stories.js", "manifest.webmanifest", "sw.js", "icon.svg"]
REQUIRED = {"id", "title", "subtitle", "category", "tags", "minutes", "intro", "reflection", "sources"}
def source_url(src):
    return src[1] if isinstance(src, list) and len(src) > 1 else (src.get("url", "") if isinstance(src, dict) else "")
def main():
    paths = sorted(ARTICLES.glob("*.json"))
    stories=[]; ids=set(); errors=[]
    for path in paths:
        try: story=json.loads(path.read_text(encoding="utf-8"))
        except Exception as e:
            errors.append(f"{path.name}: JSON 讀取失敗：{e}"); continue
        missing=REQUIRED-set(story)
        if missing: errors.append(f"{path.name}: 缺少欄位 {', '.join(sorted(missing))}")
        if not story.get("body") and not isinstance(story.get("sections"), list): errors.append(f"{path.name}: 必須有 body 或 sections")
        if not story.get("id") or story["id"] in ids: errors.append(f"{path.name}: id 空白或重複：{story.get('id')}")
        ids.add(story.get("id"))
        if not isinstance(story.get("tags"), list): errors.append(f"{path.name}: tags 必須是陣列")
        if not isinstance(story.get("sources"), list) or len(story.get("sources", [])) < 2: errors.append(f"{path.name}: 至少列出 2 個來源")
        for src in story.get("sources", []):
            url=source_url(src)
            if not isinstance(url, str) or not url.startswith("https://"):
                errors.append(f"{path.name}: 來源連結必須使用 HTTPS：{url}")
        stories.append(story)
    if errors:
        print("內容檢查失敗：\n- " + "\n- ".join(errors), file=sys.stderr); return 1
    import re as _re
    for i, story in enumerate(stories, 1):
        story["num"] = f"{i:03d}"
        # Reading time from actual content length (~350 zh chars/min), so labels
        # never drift from the real article; the JSON "minutes" field is a fallback only.
        if isinstance(story.get("sections"), list):
            text = story.get("intro", "") + "".join(
                para for sec in story["sections"] for para in sec.get("paragraphs", []))
        else:
            text = story.get("intro", "") + _re.sub(r"<[^>]+>", "", story.get("body", ""))
        story["minutes"] = max(1, round(len(_re.sub(r"\s", "", text)) / 350))
    (ROOT/"stories.js").write_text("// Generated by scripts/build_site.py. Edit content/articles/*.json instead.\nwindow.FARAWAY_STORIES = "+json.dumps(stories, ensure_ascii=False, separators=(",", ":"))+";\n", encoding="utf-8")
    dist=ROOT/"dist"
    if dist.exists(): shutil.rmtree(dist)
    dist.mkdir()
    for name in ASSETS: shutil.copy2(ROOT/name, dist/name)
    (dist/".nojekyll").write_text("", encoding="utf-8")
    print(f"完成：驗證 {len(stories)} 篇文章，網站檔案輸出至 dist/。")
    return 0
if __name__ == "__main__": raise SystemExit(main())
